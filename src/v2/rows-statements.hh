// G12: a local's slot is taken where its declaration is met, one for
// the whole activation, never shared and never given back at its
// block's end, so siblings do not share one.  Without an initializer
// nothing is stored, and the slot holds what it holds, G5.
template< typename S, view_t V >
void
generate(S &s, const decl_t< V > &d)
{
    allocate(s, d.where, V);
}

// An array's slot, rcc's allocate() by the array's size and its
// element's alignment: nothing aligns an array past its element.
template< typename S >
void
generate(S &s, const array_decl_t &d)
{
    s.slots.emplace(d.where.id, allocate(s, d.size, d.align));
}

// The slot is taken before the initializer is generated, whose scope
// holds the name already, 6.2.1p7: int x = x; reads x's own slot.  The
// value is stored at the slot's address, which writes nothing.
template< typename S, view_t V >
void
generate(S &s, const init_t< V > &i)
{
    allocate(s, i.where, V);
    initialize(s, address(s, i.where), i.value);
}

// An expression statement is its expression for its effect, 6.8.4p2.
template< typename S >
void
generate(S &s, const expr_stmt_t &x)
{
    effect(s, x.e);
}

// The null statement performs no operations, 6.8.4p3.
template< typename S >
void
generate(S &, const null_t &)
{
}

// A block is its items in order, each generated by its own row.
template< typename S >
void
generate(S &s, const block_t &b)
{
    for (const stmt_t &item : b.items)
        generate(s, item);
}

// The labels of a loop, docs/backend.md 7.2: each loop takes its own
// at fixed moments, from the state's count, and records the two its
// body's jumps name under its number, before the body is generated:
// its breaks' and its continues'.
template< typename S >
void
record(S &s, int loop, int break_, int continue_)
{
    s.breaks.emplace(loop, break_);
    s.continues.emplace(loop, continue_);
}

// The label a break names, its loop's or its switch's, and the label a
// continue names, its loop's, which that statement's row recorded.
template< typename S >
int
label_of(const S &s, const break_t &b)
{
    return s.breaks.at(b.target);
}

template< typename S >
int
label_of(const S &s, const continue_t &c)
{
    return s.continues.at(c.loop);
}

// The label a return without an expression names, rcc's target_of():
// the one epilogue's, the state's ret.
template< typename S >
int
label_of(const S &s, const return_void_t &)
{
    return s.ret;
}

// The label of the C label numbered label, rcc's user_label(),
// docs/backend.md 7.2: one more label of the function, taken where the
// generation first meets the C label, at its definition, at a goto to
// it, or at an if whose then part is that goto.  No listing shows the
// C label's name.
template< typename S >
int
user_label(S &s, int label)
{
    const auto [at, added] = s.user_labels.try_emplace(label, 0);
    if (added)
        at->second = new_label(s);

    return at->second;
}

// The label a goto names, rcc's target_of(): its C label's, taken here
// where the goto is the first to meet it.
template< typename S >
int
label_of(S &s, const goto_t &g)
{
    return user_label(s, g.label);
}

// rcc's label_stmt(): a C label is placed where it is written, and is
// not aligned even where a goto jumps back to it, so a loop made of a
// goto is laid out as it is written.
template< typename S >
void
generate(S &s, const label_t &l)
{
    place_label(s, user_label(s, l.label));
}

// rcc's if_stmt(), docs/backend.md 7.2: the label past the then part
// taken on reaching the if, before any of the condition's, the
// condition's jump to it where the condition is 0, the then part, then
// the label.  An empty then part changes nothing.
template< typename S >
void
generate(S &s, const if_t<> &i)
{
    const int no = new_label(s);
    branch(s, i.cond, no, false);

    generate(s, i.then);

    place_label(s, no);
}

// The else part follows the label the condition jumps to where it is
// 0.  A then part that ends in a jump, the state terminated after it,
// takes no jump over the else part and no label past it: no path
// leaves the then part at its end to take them.  The label past the
// else part is taken after every label of the then part.
template< typename S >
void
generate(S &s, const if_else_t<> &i)
{
    const int no = new_label(s);
    branch(s, i.cond, no, false);

    generate(s, i.then);

    if (s.terminated) {
        place_label(s, no);
        generate(s, i.otherwise);
        return;
    }

    const int end = new_label(s);
    jump(s, end);

    place_label(s, no);
    generate(s, i.otherwise);

    place_label(s, end);
}

// An if whose then part is one jump, rcc's if_jump(): the condition's
// jump to the jump's label where it is nonzero, and no label of the
// if's own; the else part follows with no jump over it, as the first
// pass of the Seventh Edition compiler writes it, c02.c.  The jump's
// label is asked before anything of the condition, since a goto's is
// taken where it is first met, as rcc's body_target() asks it before
// if_stmt() takes a label.
template< typename S, one_jump J >
void
generate(S &s, const if_t< J > &i)
{
    const int target = label_of(s, i.then);
    branch(s, i.cond, target, true);
}

template< typename S, one_jump J >
void
generate(S &s, const if_else_t< J > &i)
{
    const int target = label_of(s, i.then);
    branch(s, i.cond, target, true);

    generate(s, i.otherwise);
}

// rcc's while_stmt(), G14: the condition at the head, where it is
// written, tested once per iteration and once more, with no rotation;
// the head's label and the one past the loop taken on reaching it, and
// both placed.  A continue jumps to the head.  A body that ends in a
// jump, the state terminated after it, takes no jump back: no path
// leaves the body at its end to take it.
template< typename S >
void
generate(S &s, const while_t &w)
{
    const int cond = new_label(s);
    const int end = new_label(s);
    record(s, w.loop, end, cond);

    align_loop_head(s);
    place_label(s, cond);
    branch(s, w.cond, end, false);

    generate(s, w.body);
    if (!s.terminated)
        jump(s, cond);

    place_label(s, end);
}

// rcc's do_stmt(): the body first, then the condition, where it is
// written, its jump back to the body's label, the loop's head, where it
// is nonzero.  The three labels are taken on reaching the loop.  The
// test is written where a path reaches it, out of the body's end or by
// a continue, whose label is placed only where a continue names it;
// the label past the test only where a break does.
template< typename S, bool broken, bool continued >
void
generate(S &s, const do_t< broken, continued > &d)
{
    const int body = new_label(s);
    const int cond = new_label(s);
    const int end = new_label(s);
    record(s, d.loop, end, cond);

    align_loop_head(s);
    place_label(s, body);
    generate(s, d.body);

    if constexpr (continued)
        place_label(s, cond);
    if (!s.terminated)
        branch(s, d.cond, body, true);

    if constexpr (broken)
        place_label(s, end);
}

// The test at a for's head: the condition's jump past the loop where it
// is 0; an omitted condition writes none.
template< typename S >
void
test_of_for(S &s, const expr_t &cond, int end)
{
    branch(s, cond, end, false);
}

template< typename S >
void
test_of_for(S &, const omitted_t &, int)
{
}

// Whether a for of the condition C tests it at its head,
// test_of_for()'s jump, which names the label past the loop: a
// written condition does, and an omitted one does not.
template< typename C >
constexpr bool tested = true;

template<>
constexpr bool tested< omitted_t > = false;

// rcc's for_stmt(), G14, as for while: the init, then the three labels,
// the head's, the step's and the one past the loop, then the test at
// the head.  The step and the jump back are written where a path
// reaches them, out of the body's end or by a continue, whose label,
// the step's, is placed only where a continue names it; the label past
// the loop where the test or a break names it.
template< typename S, typename C, bool broken, bool continued >
void
generate(S &s, const for_t< C, broken, continued > &f)
{
    generate(s, f.init);

    const int cond = new_label(s);
    const int next = new_label(s);
    const int end = new_label(s);
    record(s, f.loop, end, next);

    align_loop_head(s);
    place_label(s, cond);
    test_of_for(s, f.cond, end);

    generate(s, f.body);

    if constexpr (continued)
        place_label(s, next);
    if (!s.terminated) {
        generate(s, f.step);
        jump(s, cond);
    }

    if constexpr (tested< C > || broken)
        place_label(s, end);
}

// The simple form, rcc's simple_switch(), backend.md 7.3: a case's test
// for each case, each target's equal_jump(), in the order of the
// values, then the jump to otherwise, at the view of the promoted type.
template< typename S >
void
simple_switch(S &s,
              value_t v,
              const std::vector< case_t > &cases,
              view_t view,
              int otherwise)
{
    for (const case_t &c : cases)
        equal_jump(s, v, c.value, view, s.cases.at(c.label));

    release(s, v);
    jump(s, otherwise);
}

// The direct form, rcc's direct_switch(), backend.md 7.3: the first
// value subtracted where it is not 0, the result compared unsigned with
// the range and the jump to otherwise above it, then the jump through a
// table of range + 1 entries, each a case's label or otherwise.  The
// dispatch is an operation of the unsigned type of the promoted type's
// view, so the subtraction, a write of an unsigned value at that view,
// leaves the index valid to 64 bits, written(); without it the index is
// valid as the controlling expression's value is, valid.
template< typename S >
void
direct_switch(S &s,
              value_t v,
              int valid,
              const std::vector< case_t > &cases,
              view_t view,
              int otherwise)
{
    const long long first = cases.front().value;
    const unsigned long long range = case_range(cases, view);

    if (first != 0) {
        v = subtracted(s, v, first, view);
        valid = written(width(view), sign_t::unsigned_);
    }

    compare(s, v, static_cast< long long >(range), view);
    jump_if(s, binary_op_t::ugt, otherwise);

    std::vector< int > entries(range + 1, otherwise);
    for (const case_t &c : cases)
        entries[case_offset(c.value, first, view)] = s.cases.at(c.label);

    const int table = new_label(s);
    table_jump(s, v, valid, view, table);
    jump_table(s, table, entries);
}

// The size of a hash switch's table, rcc's table_size(), backend.md 7.3:
// the i from a quarter of the count of the cases to a half that makes i
// times the most cases one remainder modulo i holds the least, the first
// such i on a tie.  A value's remainder is of its bits read unsigned at
// the view, so a negative case leaves another remainder at 32 bits than
// at 64.  The hash form has ten cases or more, so i is 2 or more.
inline unsigned long long
table_size(const std::vector< case_t > &sorted, view_t view)
{
    const unsigned long long count = sorted.size();

    unsigned long long tabs = 0;
    unsigned long long best = ~0ull;
    for (unsigned long long i = count / 4; i <= count / 2; ++i) {
        std::vector< unsigned long long > held(i);
        for (const case_t &c : sorted)
            ++held[unsigned_bits(c.value, view) % i];

        const unsigned long long worst = std::ranges::max(held);
        if (i * worst < best) {
            tabs = i;
            best = i * worst;
        }
    }

    return tabs;
}

// The hash form, rcc's hash_switch(), backend.md 7.3: the value divided
// unsigned by the size of the table, each target's divided(), the jump
// through the table by the remainder to a bucket, and in each bucket a
// case's test of the quotient against each of its cases' value divided
// by the size, in the order of the values, then the jump to otherwise,
// each at the view of the promoted type.  The quotient is held across
// the table's jump and the buckets; no case's label is among them.  The
// remainder, a write of an unsigned value at the view, is valid to 64
// bits.
template< typename S >
void
hash_switch(S &s,
            value_t v,
            const std::vector< case_t > &cases,
            view_t view,
            int otherwise)
{
    const unsigned long long tabs = table_size(cases, view);
    const auto [quotient, remainder] =
        divided(s, v, static_cast< long long >(tabs), view);

    const int table = new_label(s);
    std::vector< int > buckets;
    for (unsigned long long i = 0; i < tabs; ++i)
        buckets.push_back(new_label(s));

    table_jump(s, remainder, written(width(view), sign_t::unsigned_), view,
               table);
    jump_table(s, table, buckets);

    for (unsigned long long i = 0; i < tabs; ++i) {
        place_label(s, buckets[i]);

        for (const case_t &c : cases) {
            const unsigned long long bits = unsigned_bits(c.value, view);
            if (bits % tabs == i)
                equal_jump(s, quotient, static_cast< long long >(bits / tabs),
                           view, s.cases.at(c.label));
        }

        jump(s, otherwise);
    }

    release(s, quotient);
}

// The labels of a switch's case and default labels, rcc's
// number_case_labels(): one more label of the function for each, taken
// where the generation meets the switch, in the order of the parser's
// numbers, which is the order they are written.
template< typename S >
void
number_case_labels(S &s,
                   const std::vector< case_t > &cases,
                   const std::optional< int > &default_)
{
    std::vector< int > labels;
    for (const case_t &c : cases)
        labels.push_back(c.label);
    if (default_)
        labels.push_back(*default_);

    std::ranges::sort(labels);
    for (const int n : labels)
        s.cases.emplace(n, new_label(s));
}

// rcc's switch_stmt(), backend.md 7.3: the labels of the case and
// default labels, then the label past the body, all taken on reaching
// the switch, before any of the controlling expression's; the value;
// the dispatch of the form the builder chose; the label past the body
// recorded under the switch's number for its breaks; then the body, in
// which each label is placed where it is written, and the label past it,
// which stands for the default where there is none, placed where no
// default stands or a break names it.  Every dispatch ends in a jump
// and holds no value, so no path reaches the body but by its labels.
// The dispatch is at the view of the promoted type, V, and the direct
// form's index reads what the controlling expression's value is valid
// to at that type's sign.
template< typename S, dispatch_t form, view_t V, bool defaulted, bool broken >
void
generate(S &s, const switch_t< form, V, defaulted, broken > &sw)
{
    number_case_labels(s, sw.cases, sw.default_);
    const int end = new_label(s);
    const int otherwise = sw.default_ ? s.cases.at(*sw.default_) : end;

    const value_t v = value(s, sw.cond);
    if constexpr (form == dispatch_t::direct)
        direct_switch(s, v, held_valid(s, v, sw.cond, sw.sign), sw.cases, V,
                      otherwise);
    else if constexpr (form == dispatch_t::simple)
        simple_switch(s, v, sw.cases, V, otherwise);
    else if constexpr (form == dispatch_t::hash)
        hash_switch(s, v, sw.cases, V, otherwise);
    else {
        release(s, v);
        jump(s, otherwise);
    }

    s.breaks.emplace(sw.id, end);
    generate(s, sw.body);

    if constexpr (!defaulted || broken)
        place_label(s, end);
}

// A case or a default label, rcc's case_label_stmt(): placed where it is
// written, under the label its switch's row took for its number.
template< typename S >
void
generate(S &s, const case_label_t &c)
{
    place_label(s, s.cases.at(c.label));
}

// A statement of one jump, rcc's break_stmt(), continue_stmt(),
// goto_stmt() and return_stmt() with no value: the jump to its label.
// A statement starts with no value held, so the jump is the whole of
// it.
template< typename S, one_jump J >
void
generate(S &s, const J &j)
{
    jump(s, label_of(s, j));
}

