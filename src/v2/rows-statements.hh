// -*- mode: c++; -*-

// The rows of the statements that both targets write alike: templates
// over the target's state, which name no register and write no text of
// their own.  build.cc includes this header beside the targets' rows,
// and the models instantiate each row for both targets there.

#pragma once

#include "rows-expressions.hh"
#include "stmt.hh"
#include "zoo.hh"

namespace rcc {

// G12: a local's slot is taken where its declaration is met, one for
// the whole activation, never shared and never given back at its
// block's end, so siblings do not share one.  Without an initializer
// nothing is stored, and the slot holds what it holds, G5.
template< typename S >
void
generate(S &s, const decl_t &d)
{
    allocate(s, d.where);
}

// The slot is taken before the initializer is generated, whose scope
// holds the name already, 6.2.1p7: int x = x; reads x's own slot.
template< typename S, typename V >
void
generate(S &s, const init_t< V > &i)
{
    allocate(s, i.where);
    initialize(s, i.where, i.value);
}

// A block is its items in order, each generated by its own row.
template< typename S >
void
generate(S &s, const block_t &b)
{
    for (const stmt_t &item : b.items)
        generate(s, item);
}

} // namespace rcc
